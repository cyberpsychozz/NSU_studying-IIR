/**
  * @brief This function handles EXTI line0 interrupt.
  */
void EXTI0_IRQHandler(void)
{
  /* USER CODE BEGIN EXTI0_IRQn 0 */
  static uint32_t last_tick = 0;
  uint32_t now = HAL_GetTick();

  if ((now - last_tick) >= DEBOUNCE_MS)
  {
	last_tick = now;

	/*
	 * First press:
	 *   background -> record
	 *
	 * Second press while recording:
	 *   stop recording. Record task will start playback itself.
	 */
	if ((recording == 0U) && (playback_owner == OWNER_BACKGROUND))
	{
	  playback_owner = OWNER_RECORD;

	  if (AudioQueueHandle != NULL)
	  {
		message_t msg;
		msg.type = MSG_START_RECORD;
		msg.param = 0;

		osMessageQueuePut(AudioQueueHandle, &msg, 0, 0);
	  }
	}
	else if (recording != 0U)
	{
	  recording = 0U;
	}
  }

  EXTI->PR = EXTI_PR_PR0;

  /* USER CODE END EXTI0_IRQn 0 */

  /* USER CODE BEGIN EXTI0_IRQn 1 */

  /* USER CODE END EXTI0_IRQn 1 */
}

